// 기본 대사 뒤에 추가 대사를 이어 붙인다(같은 키면 합치고 새 키는 만든다). 로드 시 1회. O(전체 대사 수)
function mergeExtraLines() {
  AGENT_PRESETS.forEach(preset => {
    Object.entries(EXTRA_LINES[preset.id] || {}).forEach(([key, extra]) => {
      preset.lines[key] = [...(preset.lines[key] || []), ...extra];
    });
  });
}
mergeExtraLines();

// 상황 대사 하나를 고른다. 해당 키가 없으면 대체 키 → idle 순으로 내려간다.
function lineFor(agentId, key, fallbackKey = "idle") {
  const lines = getPreset(agentId).lines;
  return pickRandom(lines[key]?.length ? lines[key] : lines[fallbackKey]?.length ? lines[fallbackKey] : lines.idle);
}

// 지금 시각에 맞는 혼잣말 키: 밤(23~5시)·아침(6~9시)이면 그 대사를 가끔 섞는다.
function ambientLineKey() {
  const hour = new Date().getHours();
  if ((hour >= 23 || hour < 6) && Math.random() < 0.4) return "night";
  if (hour >= 6 && hour < 10 && Math.random() < 0.4) return "morning";
  return "idle";
}
